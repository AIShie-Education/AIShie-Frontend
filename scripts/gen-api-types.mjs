#!/usr/bin/env node
// Generates src/api/generated/tools.ts from the Core tool catalogue.
//
// The catalogue is what GET /v1/tools returns: every tool's name, kind, route
// and JSON Schemas. A snapshot is kept in api/catalogue.json so that the build
// does not need a running server. To refresh it from one:
//
//   npm run gen:api -- --from https://test.aishie.app
//
// Without --from, the snapshot is read as it is.
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { compile } from 'json-schema-to-typescript'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const snapshot = resolve(root, 'api/catalogue.json')
const out = resolve(root, 'src/api/generated/tools.ts')

const fromIdx = process.argv.indexOf('--from')
let catalogue
if (fromIdx !== -1) {
  const base = process.argv[fromIdx + 1]?.replace(/\/+$/, '')
  if (!base) throw new Error('--from needs the server origin, e.g. https://test.aishie.app')
  const res = await fetch(`${base}/v1/tools`)
  if (!res.ok) throw new Error(`GET ${base}/v1/tools: ${res.status}`)
  const body = await res.json()
  catalogue = { tools: [...body.tools].sort((a, b) => a.name.localeCompare(b.name)) }
  await writeFile(snapshot, JSON.stringify(sortKeys(catalogue), null, 2) + '\n')
  console.log(`snapshot updated from ${base}: ${catalogue.tools.length} tools`)
} else {
  catalogue = JSON.parse(await readFile(snapshot, 'utf8'))
}

function sortKeys(v) {
  if (Array.isArray(v)) return v.map(sortKeys)
  if (v && typeof v === 'object') {
    return Object.fromEntries(Object.keys(v).sort().map((k) => [k, sortKeys(v[k])]))
  }
  return v
}

// course.get → CourseGet; member.update_perms → MemberUpdatePerms
function typeName(tool) {
  return tool.name
    .split(/[._]/)
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join('')
}

// Go's schema inference gives an empty input struct no properties at all.
function normalise(schema) {
  const s = structuredClone(schema ?? {})
  if (!s.type) s.type = 'object'
  if (s.type === 'object' && !s.properties) s.properties = {}
  if (s.additionalProperties === undefined) s.additionalProperties = false
  return s
}

const opts = {
  bannerComment: '',
  additionalProperties: false,
  strictIndexSignatures: true,
  format: true,
  style: { semi: false, singleQuote: true, printWidth: 110 },
  unknownAny: true,
}

let body = `/* eslint-disable */
// Generated by scripts/gen-api-types.mjs from api/catalogue.json — do not edit.
// Every tool in AIShiteru Core's catalogue (GET /v1/tools), with its input and
// output types and its REST route.

`
const entries = []
for (const tool of catalogue.tools) {
  const name = typeName(tool)
  const inTs = await compile(normalise(tool.input_schema), `${name}In`, opts)
  const outTs = await compile(normalise(tool.output_schema), `${name}Out`, opts)
  body += `/** ${tool.name} (${tool.kind}): ${tool.description.replace(/\*\//g, '*\\/')} */\n`
  body += inTs.trim() + '\n' + outTs.trim() + '\n\n'
  entries.push({ tool, name })
}

body += `export interface ToolMap {\n`
for (const { tool, name } of entries) {
  body += `  '${tool.name}': { in: ${name}In; out: ${name}Out; kind: '${tool.kind}' }\n`
}
body += `}\n\nexport type ToolName = keyof ToolMap\n\n`
body += `export interface ToolRoute {\n  method: 'GET' | 'POST'\n  path: string\n  kind: 'read' | 'write'\n}\n\n`
body += `export const TOOL_ROUTES: { readonly [K in ToolName]: ToolRoute } = {\n`
for (const { tool } of entries) {
  body += `  '${tool.name}': { method: '${tool.method}', path: '${tool.path}', kind: '${tool.kind}' },\n`
}
body += `}\n`

await mkdir(dirname(out), { recursive: true })
await writeFile(out, body)
console.log(`wrote ${out}: ${entries.length} tools`)
